function interpolate(message: string, params?: TranslationParams): string {
  if (!params) return message;
  return message.replace(/\{\{(\w+)\}\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match,
  );
}

export function translate(
  locale: AppLocale,
  english: string,
  params?: TranslationParams,
): string {
  const message = locale === "zh-CN" ? zhCN[english] ?? english : english;
  return interpolate(message, params);
}

export function resolveLanguagePreference(
  preference: LanguagePreference,
  systemLanguages?: readonly string[],
): AppLocale {
  if (preference !== "system") return preference;
  const languages = systemLanguages ?? (
    typeof navigator === "undefined"
      ? []
      : navigator.languages?.length
        ? navigator.languages
        : [navigator.language]
  );
  return languages[0]?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function loadLanguagePreference(storage?: LanguageStorage): LanguagePreference {
  const target = storage ?? (typeof window === "undefined" ? undefined : window.localStorage);
  if (!target) return "system";
  try {
    const value = target.getItem(LANGUAGE_PREFERENCE_STORAGE_KEY);
    return value === "system" || value === "zh-CN" || value === "en" ? value : "system";
  } catch {
    return "system";
  }
}

export function saveLanguagePreference(
  preference: LanguagePreference,
  storage?: LanguageStorage,
): void {
  const target = storage ?? (typeof window === "undefined" ? undefined : window.localStorage);
  if (!target) return;
  try {
    target.setItem(LANGUAGE_PREFERENCE_STORAGE_KEY, preference);
  } catch {
    // A private or locked-down webview may reject localStorage writes.
  }
}

export interface I18nContextValue {
  language: LanguagePreference;
  locale: AppLocale;
  setLanguage: (language: LanguagePreference) => void;
  t: (english: string, params?: TranslationParams) => string;
}

const defaultContext: I18nContextValue = {
  language: "system",
  locale: "en",
  setLanguage: () => {},
  t: (english, params) => translate("en", english, params),
};

const I18nContext = createContext<I18nContextValue>(defaultContext);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<LanguagePreference>(loadLanguagePreference);
  const [systemRevision, setSystemRevision] = useState(0);
  const locale = useMemo(
    () => resolveLanguagePreference(language),
    [language, systemRevision],
  );

  useEffect(() => {
    if (language !== "system") return;
    const refresh = () => setSystemRevision((revision) => revision + 1);
    window.addEventListener("languagechange", refresh);
    return () => window.removeEventListener("languagechange", refresh);
  }, [language]);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLanguage = useCallback((next: LanguagePreference) => {
    saveLanguagePreference(next);
    setLanguageState(next);
  }, []);
  const t = useCallback(
    (english: string, params?: TranslationParams) => translate(locale, english, params),
    [locale],
  );
  const value = useMemo(
    () => ({ language, locale, setLanguage, t }),
    [language, locale, setLanguage, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
